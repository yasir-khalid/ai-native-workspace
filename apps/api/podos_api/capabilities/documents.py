"""Deterministic DOCX/PPTX renderers (capability-documents).

Input is a typed ``DocumentSpec``; output is bytes. No model is involved, and
binary bodies never pass through agent/model context.
"""

from __future__ import annotations

import io

from docx import Document
from docx.shared import Pt, RGBColor
from podos_contracts.models import DocumentSpec
from pptx import Presentation
from pptx.dml.color import RGBColor as PptxRGB
from pptx.util import Emu, Inches
from pptx.util import Pt as PPt

INK = (0x14, 0x1B, 0x2D)
MUTED = (0x5B, 0x64, 0x76)
ACCENT = (0x2F, 0x5B, 0xEA)


def _banner(spec: DocumentSpec, pod_label: str) -> str:
    return f"{spec.classification.value.replace('_', ' ').upper()} · {pod_label} · Generated by PodOS"


def render_pptx(spec: DocumentSpec, *, pod_label: str) -> bytes:
    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
    blank = prs.slide_layouts[6]

    def add_text(slide, text, left, top, width, height, size, bold=False, color=INK):
        box = slide.shapes.add_textbox(left, top, width, height)
        tf = box.text_frame
        tf.word_wrap = True
        p = tf.paragraphs[0]
        p.text = text
        p.font.size = PPt(size)
        p.font.bold = bold
        p.font.color.rgb = PptxRGB(*color)
        return tf

    def footer(slide):
        add_text(slide, _banner(spec, pod_label), Inches(0.6), Inches(6.9), Inches(12), Inches(0.4), 10, color=MUTED)

    def accent_bar(slide):
        bar = slide.shapes.add_shape(1, Inches(0.6), Inches(0.55), Inches(0.12), Inches(0.75))
        bar.fill.solid()
        bar.fill.fore_color.rgb = PptxRGB(*ACCENT)
        bar.line.fill.background()

    s = prs.slides.add_slide(blank)
    accent_bar(s)
    add_text(s, spec.title, Inches(0.95), Inches(2.4), Inches(11.5), Inches(1.4), 40, bold=True)
    if spec.subtitle:
        add_text(s, spec.subtitle, Inches(0.95), Inches(3.8), Inches(11.5), Inches(1.0), 20, color=MUTED)
    footer(s)

    for sl in spec.slides:
        s = prs.slides.add_slide(blank)
        accent_bar(s)
        add_text(s, sl.title, Inches(0.95), Inches(0.5), Inches(11.5), Inches(0.9), 28, bold=True)
        box = s.shapes.add_textbox(Inches(0.95), Inches(1.6), Inches(11.6), Inches(5.0))
        tf = box.text_frame
        tf.word_wrap = True
        for i, b in enumerate(sl.bullets):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.text = f"•  {b}"
            p.font.size = PPt(18)
            p.font.color.rgb = PptxRGB(*INK)
            p.space_after = Emu(PPt(10))
        footer(s)

    if spec.citations:
        s = prs.slides.add_slide(blank)
        accent_bar(s)
        add_text(s, "Sources", Inches(0.95), Inches(0.5), Inches(11.5), Inches(0.9), 28, bold=True)
        box = s.shapes.add_textbox(Inches(0.95), Inches(1.6), Inches(11.6), Inches(5.0))
        tf = box.text_frame
        tf.word_wrap = True
        for i, c in enumerate(spec.citations):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.text = f"[{c.ref}] {c.title} — {c.source} ({(c.published_at or '')[:10]})"
            p.font.size = PPt(14)
            p.font.color.rgb = PptxRGB(*MUTED)
        footer(s)

    buf = io.BytesIO()
    prs.save(buf)
    return buf.getvalue()


def render_docx(spec: DocumentSpec, *, pod_label: str) -> bytes:
    doc = Document()
    banner = doc.add_paragraph(_banner(spec, pod_label))
    banner.runs[0].font.size = Pt(8)
    banner.runs[0].font.color.rgb = RGBColor(*MUTED)
    doc.add_heading(spec.title, level=0)
    if spec.subtitle:
        doc.add_paragraph(spec.subtitle).runs[0].italic = True
    for section in spec.sections or spec.slides:
        doc.add_heading(section.title, level=1)
        for b in section.bullets:
            doc.add_paragraph(b, style="List Bullet")
    if spec.citations:
        doc.add_heading("Sources", level=1)
        for c in spec.citations:
            doc.add_paragraph(f"[{c.ref}] {c.title} — {c.source} ({(c.published_at or '')[:10]})")
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


RENDERERS = {
    "document.export.pptx": (
        render_pptx, "application/vnd.openxmlformats-officedocument.presentationml.presentation", "pptx",
    ),
    "document.export.docx": (
        render_docx, "application/vnd.openxmlformats-officedocument.wordprocessingml.document", "docx",
    ),
}
