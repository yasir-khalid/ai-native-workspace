"""Provision the per-pod data plane (idempotent). Run once after `docker compose up`.

    uv run python -m podos_api.provision

Uses the *admin* credentials of OpenSearch/MinIO (bootstrap only) to create, for
every pod in config/iam.json:

- OpenSearch role ``podos_<pod>`` limited to indexes ``research-<pod>`` and
  ``test-research-<pod>``, an internal user ``svc-research-<pod>`` and mapping.
- MinIO buckets, an IAM policy limited to ``<bucket>/pods/<pod>/*`` and an access
  key for the pod.

Generated per-pod credentials are written to config/data_plane.dev.json, which is
the only data-plane secret the API/worker runtime reads. Admin credentials never
reach the runtime.
"""

from __future__ import annotations

import json
import os
import secrets
import string
import time

import httpx
from minio import Minio
from minio.credentials import StaticProvider
from minio.minioadmin import MinioAdmin

from .settings import get_settings

OS_ADMIN = ("admin", os.environ.get("OPENSEARCH_ADMIN_PASSWORD", "Qv7#Lumen-Ridge-41x"))
MINIO_ROOT = (os.environ.get("MINIO_ROOT_USER", "podos-root"), os.environ.get("MINIO_ROOT_PASSWORD", "podos-root-secret-2026"))
NAMESPACES = ["", "test-"]
BUCKETS = ["podos-artifacts", "podos-artifacts-test"]


def _pw(n: int = 24) -> str:
    alphabet = string.ascii_letters + string.digits
    core = "".join(secrets.choice(alphabet) for _ in range(n))
    return f"Pd{core}#9x"


def _wait(fn, what: str, tries: int = 60) -> None:
    for _ in range(tries):
        try:
            fn()
            return
        except Exception:  # noqa: BLE001
            time.sleep(2)
    raise SystemExit(f"{what} not reachable")


def provision() -> dict:
    s = get_settings()
    pods = [p["pod_id"] for p in json.loads((s.config_dir / "iam.json").read_text())["pods"]]
    path = s.data_plane_secrets_path
    secrets_doc = json.loads(path.read_text()) if path.exists() else {}
    secrets_doc.setdefault("_comment", "DEV ONLY. Generated by podos_api.provision: one scoped credential per pod per service.")
    os_creds = secrets_doc.setdefault("opensearch", {})
    s3_creds = secrets_doc.setdefault("s3", {})

    # ---------------- OpenSearch ----------------
    hc = httpx.Client(base_url=s.opensearch_url, auth=OS_ADMIN, verify=False, timeout=15)
    _wait(lambda: hc.get("/_cluster/health").raise_for_status(), "OpenSearch")
    for pod in pods:
        cred = os_creds.setdefault(pod, {"username": f"svc-research-{pod}", "password": _pw()})
        role = f"podos_{pod}"
        patterns = [f"{ns}research-{pod}" for ns in NAMESPACES]
        r = hc.put(f"/_plugins/_security/api/roles/{role}", json={
            "cluster_permissions": ["cluster_monitor"],
            "index_permissions": [{"index_patterns": patterns, "allowed_actions": ["indices_all"]}],
        })
        r.raise_for_status()
        r = hc.put(f"/_plugins/_security/api/internalusers/{cred['username']}",
                   json={"password": cred["password"], "backend_roles": [], "attributes": {"pod_id": pod}})
        r.raise_for_status()
        r = hc.put(f"/_plugins/_security/api/rolesmapping/{role}", json={"users": [cred["username"]]})
        r.raise_for_status()

    # ---------------- MinIO ----------------
    root = Minio(s.s3_endpoint, access_key=MINIO_ROOT[0], secret_key=MINIO_ROOT[1], secure=s.s3_secure)
    _wait(lambda: root.list_buckets(), "MinIO")
    for b in BUCKETS:
        if not root.bucket_exists(b):
            root.make_bucket(b)
    admin = MinioAdmin(endpoint=s.s3_endpoint, credentials=StaticProvider(*MINIO_ROOT), secure=s.s3_secure)
    for pod in pods:
        cred = s3_creds.setdefault(pod, {"access_key": f"podos-{pod}".replace("_", "-"), "secret_key": _pw(32)})
        policy = {
            "Version": "2012-10-17",
            "Statement": [{
                "Effect": "Allow",
                "Action": ["s3:GetObject", "s3:PutObject"],
                "Resource": [f"arn:aws:s3:::{b}/pods/{pod}/*" for b in BUCKETS],
            }],
        }
        admin.policy_add(f"podos-{pod}", policy=policy)
        admin.user_add(cred["access_key"], cred["secret_key"])
        admin.policy_set(f"podos-{pod}", user=cred["access_key"])

    path.write_text(json.dumps(secrets_doc, indent=2))
    os.chmod(path, 0o600)
    return {"pods": pods, "secrets_file": str(path)}


if __name__ == "__main__":
    print(provision())
