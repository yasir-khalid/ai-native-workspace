// Generates the agents' OpenUI system-prompt section from lib/openui/spec.json, and validates the
// examples with the real OpenUI parser.
//   node scripts/openui-prompt.mjs           write ../../config/openui/system-prompt.md
//   node scripts/openui-prompt.mjs --check   fail if the committed prompt is stale or an example doesn't parse
import { readFileSync, writeFileSync } from "node:fs";
import { createParser } from "@openuidev/react-lang";
import { openuiLibrary } from "@openuidev/react-ui";

const spec = JSON.parse(readFileSync(new URL("../lib/openui/spec.json", import.meta.url)));
const keep = new Set(spec.keep);
const lib = openuiLibrary.extend({ components: { remove: Object.keys(openuiLibrary.components).filter((n) => !keep.has(n)) } });

const parser = createParser(lib.toJSONSchema(), lib.root);
for (const [i, ex] of spec.examples.entries()) {
  const res = parser.parse(ex);
  const errors = res?.meta?.errors ?? [];
  if (!res?.root || errors.length) {
    console.error(`example ${i} does not parse:`, JSON.stringify(errors).slice(0, 500));
    process.exit(1);
  }
}

const prompt = lib.prompt({
  preamble: spec.preamble, additionalRules: spec.rules, examples: spec.examples,
  inlineMode: true, toolCalls: false, bindings: false, builtinFunctions: false,
});
// PodOS never lets generated UI navigate anywhere: drop the built-in @OpenUrl step from the prompt (the
// renderer's onAction also ignores it). Our own rule that forbids it stays.
const cleaned = prompt
  .replaceAll("(@ToAssistant, @OpenUrl)", "(@ToAssistant)")
  .replace(/, e\.g\. Button\("Read", Action\(\[@OpenUrl\([^)]*\), @ToAssistant\("[^"]*"\)\]\)\)/, "")
  .split("\n")
  .filter((line) => !/^- @OpenUrl\(|@OpenUrl\("https?:/.test(line) && line.trim() !== "Example — simple nav:")
  .join("\n")
  .replace(/\n```\n```\n/g, "\n");
const out = new URL("../../../config/openui/system-prompt.md", import.meta.url);
const header = "<!-- GENERATED by apps/web/scripts/openui-prompt.mjs from apps/web/lib/openui/spec.json. Do not edit. -->\n";
const text = header + cleaned.trim() + "\n";
if (process.argv.includes("--check")) {
  const current = (() => { try { return readFileSync(out, "utf8"); } catch { return ""; } })();
  if (current !== text) {
    console.error("config/openui/system-prompt.md is stale: run `npm run openui:prompt` in apps/web");
    process.exit(1);
  }
  console.log(`openui prompt up to date (${text.length} chars, ${spec.examples.length} examples parse)`);
} else {
  writeFileSync(out, text);
  console.log(`wrote config/openui/system-prompt.md (${text.length} chars)`);
}
